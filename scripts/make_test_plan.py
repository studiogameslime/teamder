# auto-fill bug rows: any test with a real bug (failed/partial, OR a
# bug that was already fixed in-place during testing → status 'תוקן').
bug_rows = []
for tid, area, scen, steps, exp in TESTS:
    r = RESULTS.get(tid, {})
    has_bug = bool(r.get("bug"))
    failed = r.get("status") in ("נכשל", "חלקי")
    if not (has_bug or (failed and r.get("note"))):
        continue
    # A bug noted on a passing test means it was found AND fixed.
    state = "תוקן" if (has_bug and r.get("fix") and r.get("status") == "עבר") else "חדש"
    bug_rows.append((
        tid, scen, r.get("bug", r.get("note", "")),
        r.get("severity", ""), r.get("repro", steps),
        state, r.get("fix", ""),
    ))
