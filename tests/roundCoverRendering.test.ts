describe('the same round has the same source in the list and details', () => {
  function both(g: Game, cover?: { coverPhotoUrl?: string; coverImageId?: string } | null, loading = false) {
    const list = image(MatchListCard({ game: g, userId: 'u1', onPrimary: () => {}, cover, coverLoading: loading }));
    const hero = image(MatchStadiumHero({ roundId: g.id, fieldType: g.fieldType,
      startsAt: g.startsAt, groupId: g.isOrphanContext ? undefined : g.groupId, coverUrl: g.isOrphanContext ? undefined : cover?.coverPhotoUrl,
      coverImageId: g.isOrphanContext ? undefined : cover?.coverImageId, coverLoading: loading, onBackPress: () => {} }));
    const home = image(UpcomingRoundCard({ game: g, state: deriveRoundState(g, 'u1', 0), now: 0, cover, coverLoading: loading,
      actions: { onDetails: () => {}, onJoin: () => {}, onSummary: () => {}, onCreate: () => {}, onFind: () => {} } }));
    expect(home.source).toEqual(hero.source);
    return { list, hero, home };
  }
  it.each(['asphalt', 'synthetic', 'grass', undefined] as const)('shares the stable surface/gallery choice for %s', (fieldType) => {
    for (const cover of [null, { coverImageId: 'c12' }, { coverPhotoUrl: 'uploaded', coverImageId: 'c12' }]) {
      const { list, hero } = both({ ...game, fieldType }, cover);
      expect(hero.source).toEqual(list.source);
      expect(hero.source).toBeDefined();
    }
  });
  it.each(['asphalt', 'synthetic', 'grass'] as const)('shares day/night covers in all three components for %s', fieldType => {
    for (const [time,period] of [['2026-07-15T12:00:00+03:00','day'],['2026-07-15T21:00:00+03:00','night']] as const) {
      const { list,hero,home } = both({...game,fieldType,startsAt:Date.parse(time)},null);
      expect(list.source).toMatch(new RegExp(`^${fieldType}-${period}-`));
      expect(list.source).toEqual(hero.source); expect(list.source).toEqual(home.source);
    }
  });
  it('shares pending, failed-upload and changed-upload handling', () => {
    const g = { ...game, fieldType: 'synthetic' as const };
    const pending = both(g, undefined, true);
    expect(pending.list.source).toBeUndefined(); expect(pending.hero.source).toBeUndefined();
    const broken = both(g, { coverPhotoUrl: 'broken', coverImageId: 'c12' });
    broken.list.onError(); broken.hero.onError();
    const fallback = both(g, { coverPhotoUrl: 'broken', coverImageId: 'c12' });
    expect(fallback.list.source).toBe(roundSurfaceCover(g.fieldType, g.id, g.startsAt));
    expect(fallback.hero.source).toEqual(fallback.list.source);
    const changed = both(g, { coverPhotoUrl: 'new' });
    broken.hero.onError();
    expect(mockFailed).toBe('broken');
    expect(changed.hero.source).toEqual({ uri: 'new' });
  });
  it('shares standalone and orphan fallbacks', () => {
    for (const g of [{ ...game, groupId: '' }, { ...game, isOrphanContext: true }]) {
      const { list, hero } = both(g, null);
      expect(hero.source).toEqual(list.source);
      expect(hero.source).toBe('default-cover');
    }
  });
  it('the screen passes the actual round identity and surface to its hero', () => {
    const source = fs.readFileSync('src/screens/games/MatchDetailsScreen.tsx', 'utf8');
    expect(source).toMatch(/<MatchStadiumHero\s+roundId=\{game.id\}\s+fieldType=\{game.fieldType\}/);
  });
});
